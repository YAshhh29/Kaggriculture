def crop_can_mature(crop: str, planted_day: int, day: int) -> bool:
    """Will a tile planted on `planted_day` ever pay out before the end?

    This is the strawberry question: a crop whose first yield lands after
    the season ends is worth nothing at all, so no watering, fertilizing
    or harvesting effort spent on it can be justified.
    """
    spec = CROPS.get(crop)
    if spec is None:
        return False
    return planted_day + spec['first'] <= LAST_DAY

def remaining_waterings(crop: str, planted_day: int, day: int) -> int:
    """How many more yield-producing waterings this tile can still take.

    Non-ongoing crops only gain yield when watered inside
    [(max_day+1)//2, max_day] days of age; ongoing crops accrue on their
    own interval instead, so watering them protects the plant rather than
    adding units.
    """
    spec = CROPS.get(crop)
    if spec is None:
        return 0
    age = day - planted_day
    if spec['ongoing']:
        return max(0, min(days_left(day), spec['max_yield']))
    start = (spec['max_day'] + 1) // 2
    last = min(spec['max_day'], spec['max_day'] + days_left(day) - (age - age))
    if age > spec['max_day']:
        return 0
    first_open = max(age, start)
    return max(0, min(last, LAST_DAY - day + age) - first_open + 1)

def water_value(observation: dict[str, Any], tile: dict[str, Any], day: int) -> float:
    """Coins gained by watering this tile now."""
    crop = str(tile.get('crop', ''))
    spec = CROPS.get(crop)
    if spec is None:
        return 0.0
    planted = int(tile.get('planted_day', day))
    if not crop_can_mature(crop, planted, day):
        return 0.0
    price = live_price(observation, crop)
    fertilized = int(tile.get('fertilized_until_day', -1)) >= day
    units = 2.0 if fertilized else 1.0
    if spec['ongoing']:
        at_risk = int(tile.get('consecutive_unwatered', 0)) >= 1
        return price * units if at_risk else price * 0.25
    age = day - planted
    start = (spec['max_day'] + 1) // 2
    if age < start or age > spec['max_day']:
        at_risk = int(tile.get('consecutive_unwatered', 0)) >= 1
        return price * 0.5 if at_risk else 0.0
    held = int(tile.get('yield_units', 0))
    if held >= spec['max_yield']:
        return 0.0
    gained = min(units, spec['max_yield'] - held)
    return price * gained

def fertilize_value(observation: dict[str, Any], tile: dict[str, Any], day: int) -> float:
    """Coins gained by fertilizing, net of selling the fertilizer instead.

    Fertilizer doubles the yield each watering adds, for three days. Its
    worth is therefore the number of yield-adding waterings still available
    inside that window, times the crop price -- minus what the unit would
    have fetched on the market.
    """
    crop = str(tile.get('crop', ''))
    spec = CROPS.get(crop)
    if spec is None:
        return 0.0
    planted = int(tile.get('planted_day', day))
    if not crop_can_mature(crop, planted, day):
        return 0.0
    if int(tile.get('fertilized_until_day', -1)) >= day:
        return 0.0
    held = int(tile.get('yield_units', 0))
    headroom = max(0, spec['max_yield'] - held)
    if headroom <= 0:
        return 0.0
    age = day - planted
    if spec['ongoing']:
        boosted = min(3, days_left(day), headroom)
    else:
        start = (spec['max_day'] + 1) // 2
        window_end = min(spec['max_day'], age + 2)
        boosted = max(0, window_end - max(age, start) + 1)
        boosted = min(boosted, headroom, days_left(day))
    if boosted <= 0:
        return 0.0
    gain = live_price(observation, crop) * boosted
    return gain - live_price(observation, 'FERTILIZER')

def harvest_value(observation: dict[str, Any], tile: dict[str, Any], day: int | None=None) -> float:
    """Coins realisable from the units sitting on this tile.

    For a non-ongoing crop the simulator *destroys the plant* on harvest
    (`farm["tiles"][fy][fx] = None`), so picking wheat holding one unit
    when it could still reach six throws five units away. Valuing a
    harvest at its face amount made an agent harvest 1,714 times for 0.2
    units apiece where a good route harvests 450 times for 4.75. So an
    early harvest is priced at what it actually nets: the units in hand
    minus the units forfeited by ending the plant now.

    Animals and ongoing crops keep producing after collection, so for them
    the face value is correct.
    """
    units = int(tile.get('yield_units', 0))
    if units <= 0:
        return 0.0
    if 'animal' in tile:
        product = ANIMALS[str(tile['animal'])]['product']
        return live_price(observation, product) * units
    crop = str(tile.get('crop', ''))
    spec = CROPS.get(crop)
    price = live_price(observation, crop)
    if spec is None:
        return price * units
    if spec['ongoing']:
        return price * units
    if day is None:
        return price * units
    planted = int(tile.get('planted_day', day))
    if day - planted < spec['first']:
        return 0.0
    headroom = spec['max_yield'] - units
    if headroom <= 0:
        return price * units
    age = day - planted
    window_start = (spec['max_day'] + 1) // 2
    per_watering = 2 if int(tile.get('fertilized_until_day', -1)) >= day else 1
    today = 1 if not tile.get('watered_today') and window_start <= age <= spec['max_day'] else 0
    last_window_day = min(planted + spec['max_day'], LAST_DAY)
    future = max(0, last_window_day - day)
    forfeited = min(headroom, (today + future) * per_watering)
    if forfeited <= 0:
        return price * units
    return price * units - price * forfeited

def feed_value(observation: dict[str, Any], tile: dict[str, Any], day: int) -> float:
    """Coins protected by feeding this animal now.

    Two separate things hang on a feed, and an earlier version priced
    neither properly.

    An animal unfed for two consecutive days escapes and the structure is
    emptied, forfeiting every remaining unit it would have produced *and*
    the one fertilizer it drops every single day for the rest of the
    season. Pricing that loss from the product's spot quote alone made
    feeding look worthless the moment milk or wool bottomed out at a coin,
    so this agent fed its herd 188 times where it needed 450, bought
    thirty-one animals and finished with eighteen. Fertilizer keeps its
    value long after milk does, so it belongs in the number.

    Short of that, feeding is what unlocks the care bonus: the simulator
    only pays out banked care on a day the animal was fed, so a fed and
    cared animal yields (interval + 1) units every `interval` days against
    the single unit an ignored one still produces. Feeding a goose doubles
    it, a cow triples it, a sheep quadruples it.
    """
    animal = str(tile.get('animal', ''))
    spec = ANIMALS.get(animal)
    if spec is None or tile.get('fed_today'):
        return 0.0
    remaining = days_left(day)
    if remaining <= 0:
        return 0.0
    interval = max(1, int(spec['interval']))
    price = marginal_price(observation, spec['product'])
    manure = marginal_price(observation, 'FERTILIZER')
    if int(tile.get('consecutive_unfed', 0)) >= 1:
        kept = (interval + 1.0) / interval
        return price * kept * remaining + manure * remaining
    return price * (remaining / interval)

def care_value(observation: dict[str, Any], tile: dict[str, Any], day: int) -> float:
    """Care adds one bonus unit on the next fed production day."""
    animal = str(tile.get('animal', ''))
    spec = ANIMALS.get(animal)
    if spec is None or tile.get('cared_today'):
        return 0.0
    if days_left(day) <= 0:
        return 0.0
    if int(tile.get('yield_units', 0)) >= spec['max_held']:
        return 0.0
    return live_price(observation, spec['product'])

def collect_fertilizer_value(observation: dict[str, Any], tile: dict[str, Any]) -> float:
    """A collected unit is worth whatever the best use of it is."""
    if not tile.get('fertilizer_available'):
        return 0.0
    return live_price(observation, 'FERTILIZER')

def plant_value(observation: dict[str, Any], crop: str, day: int) -> float:
    """Expected coins from starting this crop now, net of the seed.

    Returns 0 for a crop that cannot reach its first yield before the
    season ends, which is what stops the agent sinking worker-turns into
    a strawberry that will never pay.
    """
    spec = CROPS.get(crop)
    if spec is None or not crop_can_mature(crop, day, day):
        return 0.0
    price = live_price(observation, crop)
    if spec['ongoing']:
        productions = min(spec['max_yield'], max(0, (days_left(day) - spec['first']) // max(1, spec['interval']) + 1))
        units = productions
    else:
        window = min(spec['max_day'], days_left(day))
        start = (spec['max_day'] + 1) // 2
        units = min(spec['max_yield'], max(0, window - start + 1))
    return price * units - spec['seed']

def plant_tile_days(crop: str, day: int) -> float:
    """How long a tile is tied up growing this crop, in days.

    A one-shot crop occupies its tile until the last day it can still be
    harvested; an ongoing crop until it stops producing.
    """
    spec = CROPS.get(crop)
    if spec is None:
        return 1.0
    if spec['ongoing']:
        span = spec['first'] + spec['interval'] * spec['max_yield']
    else:
        span = spec['max_day']
    return float(max(1, min(span, days_left(day))))

