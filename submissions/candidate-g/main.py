def _positions(farm: dict[str, Any]) -> list[tuple[int, int]]:
    units = [farm.get('farmer'), *(farm.get('hands') or [])]
    out: list[tuple[int, int]] = []
    for unit in units:
        if isinstance(unit, (list, tuple)) and len(unit) >= 2:
            out.append((int(unit[0]), int(unit[1])))
        else:
            out.append((0, 0))
    return out

